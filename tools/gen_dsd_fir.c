/*
 * gen_dsd_fir: the DSD -> PCM decimation filters for firmware/coreb/dsd/dsd_fir.h.
 * Linear-phase low-pass FIRs (Kaiser-windowed sinc, beta 9, cut-off 24 kHz,
 * unity DC gain), 16 taps per output decimation step: 256 taps for DSD64 (/16),
 * 512 for DSD128 (/32), 1024 for DSD256 (/64) -> 176.4 kHz PCM. Q30 coefficients.
 *   cc -O2 -o gen_dsd_fir tools/gen_dsd_fir.c -lm && ./gen_dsd_fir > firmware/coreb/dsd/dsd_fir.h
 */
#include <math.h>
#include <stdio.h>

static double i0(double x)
{
    double s = 1, t = 1;

    for (int k = 1; k < 60; k++) {
        t *= (x / 2 / k) * (x / 2 / k);
        s += t;
    }
    return s;
}

int main(void)
{
    const double beta = 9.0, cut = 24000.0;

    printf("/* Generated by tools/gen_dsd_fir.c: Kaiser (beta %.0f) windowed sinc, cut-off %.0f Hz,\n"
           " * unity DC gain, Q30. One half of each symmetric filter (taps n and N-1-n are equal). */\n"
           "#ifndef RECHORD_DSD_FIR_H\n#define RECHORD_DSD_FIR_H\n#include <stdint.h>\n", beta, cut);
    for (int m = 1; m <= 4; m *= 2) {
        int n = 256 * m;
        double fs = 2822400.0 * m, fc = cut / fs, h[1024], sum = 0;

        for (int i = 0; i < n; i++) {
            double x = i - (n - 1) / 2.0, r = 2.0 * x / (n - 1);
            double s = x == 0 ? 2 * fc : sin(2 * M_PI * fc * x) / (M_PI * x);

            h[i] = s * i0(beta * sqrt(1 - r * r)) / i0(beta);
            sum += h[i];
        }
        printf("static const int32_t k_dsd_fir%d[%d] = {", n, n / 2);
        for (int i = 0; i < n / 2; i++)
            printf("%s%ld", i == 0 ? "\n    " : i % 8 ? ", " : ",\n    ", lround(h[i] / sum * 1073741824.0));
        printf("\n};\n");
    }
    printf("#endif\n");
    return 0;
}
